/** The heights of the roof triangles (flat 9-number arrays) over a point, or [] */
export function roofHeights(roof, x, z) {
  const out = [];
  for (const t of roof) {
    const d = (t[5] - t[8]) * (t[0] - t[6]) + (t[6] - t[3]) * (t[2] - t[8]);
    if (Math.abs(d) < 1e-9) continue;
    const l1 = ((t[5] - t[8]) * (x - t[6]) + (t[6] - t[3]) * (z - t[8])) / d;
    const l2 = ((t[8] - t[2]) * (x - t[6]) + (t[0] - t[6]) * (z - t[8])) / d;
    const l3 = 1 - l1 - l2;
    if (l1 < -1e-4 || l2 < -1e-4 || l3 < -1e-4) continue;
    out.push(l1 * t[1] + l2 * t[4] + l3 * t[7]);
  }
  return out;
}

// where the segment p→q (plan) crosses the segment a→b: its parameter along p→q (0–1), or null
function cross2(p, q, a, b) {
  const rx = q[0] - p[0], rz = q[1] - p[1], sx = b[0] - a[0], sz = b[1] - a[1];
  const den = rx * sz - rz * sx;
  if (Math.abs(den) < 1e-9) return null;
  const t = ((a[0] - p[0]) * sz - (a[1] - p[1]) * sx) / den, u = ((a[0] - p[0]) * rz - (a[1] - p[1]) * rx) / den;
  return t > 0 && t < 1 && u >= 0 && u <= 1 ? t : null;
}

/**
 * The top of a wall (frame F, outside on F.n) under a roof: [[s, y], …] from s 0 to F.len, the roof's underside 5 cm
 * inside the wall, with a point wherever the wall crosses a roof triangle's edge. `pick(heights)` chooses among the
 * roofs over a point (the highest for an outer wall, the lowest over its foot for a wall on a lower roof); where no
 * roof covers the wall, the roof a little further in
 */
export function wallProfile(roof, F, pick = (ys) => Math.max(...ys), inset = 0.05) {
  const p = onWall(F, 0, -inset), q = onWall(F, F.len, -inset);
  const ss = [0, F.len];
  for (const t of roof) {
    const P = [[t[0], t[2]], [t[3], t[5]], [t[6], t[8]]];
    for (let i = 0; i < 3; i++) {
      const k = cross2(p, q, P[i], P[(i + 1) % 3]);
      if (k !== null) ss.push(Math.max(0, k * F.len - 0.01), Math.min(F.len, k * F.len + 0.01));
    }
  }
  ss.sort((a, b) => a - b);
  const S = ss.filter((s, i) => i === 0 || s - ss[i - 1] > 0.004);
  if (F.len - S[S.length - 1] < 0.004) S[S.length - 1] = F.len; else S.push(F.len);
  let fallback = Infinity;
  for (const t of roof) fallback = Math.min(fallback, t[1], t[4], t[7]);
  const at = (s) => {
    for (let o = inset; o < 4.5; o += 0.25) {
      const ys = roofHeights(roof, ...onWall(F, s, -o));
      const y = ys.length ? pick(ys) : null;
      if (y !== null && Number.isFinite(y)) return y;
    }
    return fallback;
  };
  const prof = S.map((s) => [s, at(s)]);
  // (collinear points dropped)
  const out = [prof[0]];
  for (let i = 1; i < prof.length - 1; i++) {
    const a = out[out.length - 1], c = prof[i + 1], m = prof[i];
    const y = a[1] + ((m[0] - a[0]) * (c[1] - a[1])) / (c[0] - a[0] || 1);
    if (Math.abs(y - m[1]) > 0.03) out.push(m);
  }
  out.push(prof[prof.length - 1]);
  return out;
}
/** The height of a profile at s */
export function profileAt(prof, s) {
  for (let i = 0; i + 1 < prof.length; i++) {
    const [s0, y0] = prof[i], [s1, y1] = prof[i + 1];
    if (s <= s1 || i + 2 === prof.length) return s1 - s0 < 1e-6 ? Math.max(y0, y1) : y0 + ((Math.min(Math.max(s, s0), s1) - s0) * (y1 - y0)) / (s1 - s0);
  }
  return prof[0][1];
}

/** A house's outer walls: { F, part, pi } for every edge of its parts' outward rings */
export function outerWalls(h) {
  const out = [];
  h.parts.forEach((part, pi) => {
    const R = outwardRing(part.ring);
    for (let i = 0; i < R.length; i++) {
      const F = wallFrame(R[i], R[(i + 1) % R.length]);
      if (F.len > 0.05) out.push({ F, part, pi });
    }
  });
  return out;
}
/** A house's walls on lower roofs: { F, bottom }, facing the side where the roof is lower (or none); those with the
 *  same roof both sides (inside the house) left out */
export function upperWalls(h) {
  const roof = h.parts.flatMap((p) => p.roof);
  const top = (x, z) => { const ys = roofHeights(roof, x, z); return ys.length ? Math.max(...ys) : -Infinity; };
  const out = [];
  for (const [ax, az, bx, bz, bottom] of h.parts.flatMap((p) => p.upper)) {
    let F = wallFrame([ax, az], [bx, bz]);
    if (F.len < 0.05) continue;
    const o = Math.min(0.4, F.len / 3);
    let tOut = top(...onWall(F, F.len / 2, o)), tIn = top(...onWall(F, F.len / 2, -o));
    if (tOut > tIn) { F = wallFrame([bx, bz], [ax, az]); [tOut, tIn] = [tIn, tOut]; }
    if (tIn - tOut > 0.3) out.push({ F, bottom });
  }
  return out;
}
/** The outer wall of a house nearest a world point: { F, s (along it, clamped), o (its distance) } */
export function nearestWall(h, [x, z]) {
  let best = null;
  for (const { F } of outerWalls(h)) {
    if (F.len < 1.5) continue;
    const s = (x - F.a[0]) * F.u[0] + (z - F.a[1]) * F.u[1], o = (x - F.a[0]) * F.n[0] + (z - F.a[1]) * F.n[1];
    const sc = Math.min(Math.max(s, 0), F.len), d = Math.hypot(s - sc, o);
    if (!best || d < best.d) best = { F, s: sc, o, d };
  }
  return best;
}
/** A shop front's wall (its frame, outside on n) and its stretch [s0, s1] */
export function shopWall(S) {
  const h = houseOf(S.house);
  const w = outerWalls(h).find(({ F }) => {
    const [ax, az] = F.a, [bx, bz] = onWall(F, F.len);
    const near = (p, q) => Math.hypot(p[0] - q[0], p[1] - q[1]) < 0.05;
    return (near([ax, az], S.a) && near([bx, bz], S.b)) || (near([ax, az], S.b) && near([bx, bz], S.a));
  });
  if (!w) return null;
  const F = w.F, bAtStart = Math.hypot(F.a[0] - S.b[0], F.a[1] - S.b[1]) < 0.05;
  // (`from`: the share of the wall from its end at b; `to`: up to that share from a)
  let s0 = 0, s1 = F.len;
  if (S.from !== undefined) { if (bAtStart) s1 = F.len * (1 - S.from); else s0 = F.len * S.from; }
  if (S.to !== undefined) { if (bAtStart) s0 = F.len * (1 - S.to); else s1 = F.len * S.to; }
  return { F, s0, s1, part: w.part };
}


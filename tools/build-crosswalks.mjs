// tools/build-crosswalks.mjs — writes js/crosswalks-data.js: the marked pedestrian crossings (Fussgängerstreifen) of
// Davos for js/road-paint.js, which paints them yellow (Swiss SSV: bars 0.5 m wide, 0.5 m apart, 4 m long along the
// road, curb to curb).
//   - OSM highway=crossing nodes with crossing=marked|zebra|uncontrolled|traffic_signals (or crossing:markings set and
//     not "no"), read from the traffic-sign cache tools/data/cache/osm_davos_traffic_signs.json (tools/fetch-traffic-signs.mjs
//     fetches it);
//   - each placed on the drivable road it lies on (js/davos-geodata.js: the segment's direction and the road's width);
//     nodes more than 3 m off a drivable road (bridges and tunnels left out) (crossings of footpaths over cycle paths and the like) are left out, and
//     of two crossings closer than 6 m on the same road only the first is kept.
// usage: node tools/build-crosswalks.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { lonLatToWorld } from '../js/davos-frame.js';
import { DAVOS_DATA } from '../js/davos-geodata.js';

const DIR = path.dirname(fileURLToPath(import.meta.url));
const CACHE = path.join(DIR, 'data', 'cache', 'osm_davos_traffic_signs.json');
const OUT = path.join(DIR, '..', 'js', 'crosswalks-data.js');
const DRIVABLE = /^(motorway|trunk|primary|secondary|tertiary|residential|unclassified|living_street|service)(_link)?$/;
const MARKED = /^(marked|zebra|uncontrolled|traffic_signals)$/;
const r1 = (v) => Math.round(v * 10) / 10, r3 = (v) => Math.round(v * 1000) / 1000;

function nearestRoad(x, z) {
  let best = null;
  for (const road of DAVOS_DATA.roads) {
    if (!DRIVABLE.test(road.kind) || road.tunnel || road.bridge) continue;
    const p = road.pts;
    for (let i = 0; i + 3 < p.length; i += 2) {
      const ax = p[i], az = p[i + 1], bx = p[i + 2], bz = p[i + 3], dx = bx - ax, dz = bz - az, L2 = dx * dx + dz * dz;
      if (L2 < 1e-6) continue;
      const t = Math.max(0, Math.min(1, ((x - ax) * dx + (z - az) * dz) / L2));
      const d = Math.hypot(ax + dx * t - x, az + dz * t - z);
      if (!best || d < best.d) { const L = Math.sqrt(L2); best = { d, road, ux: dx / L, uz: dz / L, x: ax + dx * t, z: az + dz * t }; }
    }
  }
  return best;
}

const osm = JSON.parse(fs.readFileSync(CACHE, 'utf8'));
const out = [];
let skipped = 0;
for (const e of osm.elements) {
  const t = e.tags || {};
  if (e.type !== 'node' || t.highway !== 'crossing') continue;
  const marked = MARKED.test(t.crossing || '') || (t['crossing:markings'] && t['crossing:markings'] !== 'no');
  if (!marked || t.crossing === 'unmarked') { skipped++; continue; }
  const p = lonLatToWorld(e.lon, e.lat), r = nearestRoad(p.x, p.z);
  if (!r || r.d > 3) { skipped++; continue; }
  if (out.some((c) => c.road === r.road.id && Math.hypot(c.x - r.x, c.z - r.z) < 6)) { skipped++; continue; }
  out.push({ x: r1(r.x), z: r1(r.z), ux: r3(r.ux), uz: r3(r.uz), w: r1(r.road.width), road: r.road.id, osm: e.id });
}
out.sort((a, b) => a.osm - b.osm);
const body = out.map(({ x, z, ux, uz, w, osm: id }) => ({ x, z, ux, uz, w, osm: id }));
fs.writeFileSync(OUT, `// js/crosswalks-data.js — GENERATED by tools/build-crosswalks.mjs, do not edit by hand.
// The marked pedestrian crossings of Davos (OSM highway=crossing nodes) on the roads they cross: centre (x, z) in the
// world frame of js/davos-frame.js, the road's direction (ux, uz) and width w (metres). © OpenStreetMap contributors (ODbL).
export const CROSSWALKS = ${JSON.stringify(body)};
`);
console.log('[crosswalks]', out.length, 'crossings written,', skipped, 'left out');

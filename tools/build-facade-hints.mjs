// node tools/build-facade-hints.mjs <looks.jsonl …> → js/facade-hints-data.js
// Each input line is one OpenStreetMap building's look as read from Mapillary street photographs (CC BY-SA 4.0):
// {"id":"w…","wall":[r,g,b],"timber":0-100,"kind":"…","storeys":n,"roof":"…","roofRgb":[r,g,b],"shutters":"…",
//  "shop":bool,"balconies":bool,"confidence":0-100,…}. Lines under 50 % confidence, of buildings OpenStreetMap does
// not have, or with values out of range are left out; a later line for the same building replaces an earlier one.
// The building's outline is written with its hint (js/facade-hints.js finds the hint by the surveyed centre).
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const { DAVOS_DATA } = await import(path.join(root, 'js/davos-geodata.js'));
const byId = new Map(DAVOS_DATA.buildings.map((b) => [b.id, b]));
const KINDS = new Set(['townhouse', 'chalet', 'block', 'hotel', 'shop', 'barn', 'shed', 'church', 'office']);
const rgb = (v) => Array.isArray(v) && v.length === 3 && v.every((c) => Number.isFinite(c) && c >= 0 && c <= 255) ? v.map(Math.round) : null;

const out = {};
let read = 0, kept = 0;
for (const file of process.argv.slice(2)) {
  for (const line of fs.readFileSync(file, 'utf8').split('\n')) {
    if (!line.trim()) continue;
    read++;
    let h;
    try { h = JSON.parse(line); } catch { continue; }
    const b = byId.get(h.id);
    const wall = rgb(h.wall);
    if (!b || !wall || !(h.confidence >= 50) || !KINDS.has(h.kind)) continue;
    out[h.id] = {
      wall, timber: Math.max(0, Math.min(100, Math.round(h.timber || 0))), kind: h.kind,
      storeys: Number.isInteger(h.storeys) && h.storeys > 0 && h.storeys < 15 ? h.storeys : 0,
      roof: rgb(h.roofRgb), roofKind: ['tiles', 'slate', 'tin', 'copper', 'flat'].includes(h.roof) ? h.roof : '', shop: !!h.shop, balconies: !!h.balconies, confidence: Math.round(h.confidence),
      ring: Array.from(b.ring, (v) => Math.round(v * 10) / 10)
    };
    kept++;
  }
}
const data = { source: 'Mapillary street-level images (CC BY-SA 4.0, Mapillary contributors), read per building', buildings: out };
fs.writeFileSync(path.join(root, 'js/facade-hints-data.js'),
  `// js/facade-hints-data.js — GENERATED by tools/build-facade-hints.mjs, do not edit by hand.\n// Facade looks read from Mapillary street-level images, CC BY-SA 4.0, Mapillary contributors.\nexport const FACADE_HINTS = ${JSON.stringify(data)};\n`);
console.log(`${kept} of ${read} lines kept → js/facade-hints-data.js`);

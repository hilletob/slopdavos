// tools/build-gwr.mjs — writes js/gwr-data.js: the existing buildings of the Federal Register of Buildings and Dwellings
// (eidg. Gebäude- und Wohnungsregister, GWR) inside the Davos frame, so that js/gwr.js can give each swissBUILDINGS3D
// building the facade of its real use, age and storey count.
//  - Source: the BFS public cantonal download (https://public.madd.bfs.admin.ch/gr.zip, canton of Graubünden), table
//    gebaeude_batiment_edificio.csv (tab separated; field documentation: https://www.housing-stat.ch/de/help/42.html).
//  - Kept: GSTAT 1004 (existing) with coordinates (GKODE/GKODN, LV95) inside FRAME.lv95.
//  - Per building: x, z (world, whole metres), k = GKLAS − 1000 (building class; GKAT − 1000 where GKLAS is missing;
//    + 1000 for mixed use, GKAT 1030/1040), f = GASTW (storeys above ground, 0 unknown), y = GBAUJ (year of
//    construction; else the middle of the period GBAUP, 0 unknown).
// © BFS, Eidg. Gebäude- und Wohnungsregister (OGD, free use with source attribution). The zip is cached in
// data/hires/gwr/ (not committed).
// usage: node tools/build-gwr.mjs [--refresh]
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { FRAME, lv95ToWorld } from '../js/davos-frame.js';

const DIR = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(DIR, '..');
const CACHE = path.join(ROOT, 'data', 'hires', 'gwr');
const ZIP = path.join(CACHE, 'gr.zip');
const CSV = 'gebaeude_batiment_edificio.csv';
const OUT = path.join(ROOT, 'js', 'gwr-data.js');
const URL_GR = 'https://public.madd.bfs.admin.ch/gr.zip';
const log = (...a) => console.log('[gwr]', ...a);
fs.mkdirSync(CACHE, { recursive: true });

// The middle years of the construction periods (GBAUP)
const PERIOD = { 8011: 1900, 8012: 1932, 8013: 1953, 8014: 1965, 8015: 1975, 8016: 1983, 8017: 1988, 8018: 1993, 8019: 1998, 8020: 2003, 8021: 2008, 8022: 2013, 8023: 2019 };

if (process.argv.includes('--refresh') || !fs.existsSync(ZIP)) {
  log('downloading', URL_GR);
  const res = await fetch(URL_GR, { signal: AbortSignal.timeout(600000) });
  if (!res.ok) throw new Error(`${URL_GR}: ${res.status}`);
  fs.writeFileSync(ZIP, Buffer.from(await res.arrayBuffer()));
}
// (only the building table is extracted; nothing from the archive is executed)
execFileSync('unzip', ['-o', '-q', ZIP, CSV, '-d', CACHE]);
const lines = fs.readFileSync(path.join(CACHE, CSV), 'utf8').split(/\r?\n/);
const head = lines[0].replace(/^\uFEFF/, '').split('\t');
const col = Object.fromEntries(head.map((h, i) => [h, i]));
for (const f of ['EGID', 'GKODE', 'GKODN', 'GSTAT', 'GKAT', 'GKLAS', 'GASTW', 'GBAUJ', 'GBAUP']) if (!(f in col)) throw new Error(`no column ${f}`);

const [minE, minN, maxE, maxN] = FRAME.lv95;
const rows = [];
let total = 0, other = 0;
for (let l = 1; l < lines.length; l++) {
  if (!lines[l]) continue;
  total++;
  const c = lines[l].split('\t');
  const E = Number(c[col.GKODE]), N = Number(c[col.GKODN]);
  if (!(E >= minE && E <= maxE && N >= minN && N <= maxN)) continue;
  if (c[col.GSTAT] !== '1004') { other++; continue; }
  const { x, z } = lv95ToWorld(E, N);
  const cls = Number(c[col.GKLAS]) || Number(c[col.GKAT]) || 0;
  // (+1000: a building of mixed use, GKAT 1030/1040 — homes over shops, restaurants, offices)
  const mixed = c[col.GKAT] === '1030' || c[col.GKAT] === '1040' ? 1000 : 0;
  const year = Number(c[col.GBAUJ]) || PERIOD[c[col.GBAUP]] || 0;
  rows.push([Math.round(x), Math.round(z), cls ? cls - 1000 + mixed : 0, Math.min(99, Number(c[col.GASTW]) || 0), year]);
}
// West to east, then north to south (stable output, and the deltas stay small for gzip)
rows.sort((a, b) => a[0] - b[0] || a[1] - b[1]);
log(`${total} buildings in the canton, ${rows.length} existing in the Davos frame (${other} projected/demolished left out)`);

const pick = (i) => JSON.stringify(rows.map((r) => r[i]));
const meta = {
  source: 'Eidg. Gebäude- und Wohnungsregister (GWR), Bundesamt für Statistik BFS (public.madd.bfs.admin.ch/gr.zip)',
  license: 'OGD, free use with source attribution: © BFS, GWR',
  fetched: new Date(fs.statSync(ZIP).mtime).toISOString().slice(0, 10),
  count: rows.length
};
const text = `// js/gwr-data.js — GENERATED by tools/build-gwr.mjs, do not edit by hand.
// Existing buildings of the Federal Register of Buildings and Dwellings (GWR), © BFS: per building its world position
// (x, z, whole metres), class k (GKLAS − 1000, or GKAT − 1000; + 1000 for mixed use, GKAT 1030/1040), storeys above
// ground f (GASTW, 0 unknown) and year of construction y (GBAUJ, or the middle of its period GBAUP; 0 unknown).
export const GWR = {
  ${JSON.stringify(meta).slice(1, -1).replace(/,"/g, ',\n  "')},
  x: ${pick(0)},
  z: ${pick(1)},
  k: ${pick(2)},
  f: ${pick(3)},
  y: ${pick(4)}
};
`;
fs.writeFileSync(OUT, text);
log(`wrote ${path.relative(ROOT, OUT)} (${(text.length / 1024).toFixed(0)} KB)`);

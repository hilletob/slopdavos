// tools/detect-parking-bays.mjs — adds the painted bays seen in SWISSIMAGE to js/parking-data.js (npm run
// data:parking-bays, after data:parking). Per car park (not single bays): a crop of the lot plus 5 m from the federal
// WMS (ch.swisstopo.swissimage, 0.1 m; coarser for very large lots), cached in tools/data/cache/parking-aerial/; the
// paint lines and bays are found by tools/parking-bays.py (PIL + numpy). Lots with at least MIN_BAYS bays found get
// `bays: [[cx, cz, angle, w, l, occupied], ...]` (world frame, angle of the bay's long axis: atan2(ux, uz)); the
// others keep the procedural layout of js/parking.js.
// usage: node tools/detect-parking-bays.mjs [--debug <lot id>]
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { worldToLv95 } from '../js/davos-frame.js';
import { PARKING_DATA } from '../js/parking-data.js';

const DIR = path.dirname(fileURLToPath(import.meta.url));
const CACHE = path.join(DIR, 'data', 'cache', 'parking-aerial');
const OUT = path.join(DIR, '..', 'js', 'parking-data.js');
const WMS = 'https://wms.geo.admin.ch/';
const MARGIN = 5, RES = 0.1, MAX_PX = 3800, MIN_BAYS = 3, CONCURRENCY = 4;
const log = (...a) => console.log('[parking-bays]', ...a);
const debugAt = process.argv.indexOf('--debug');
const debugId = debugAt > 0 ? process.argv[debugAt + 1] : null;
fs.mkdirSync(CACHE, { recursive: true });

async function fetchRetry(url, file) {
  for (let attempt = 1; ; attempt++) {
    const res = await fetch(url).catch((error) => ({ ok: false, status: error.message }));
    if (res.ok && /^image\//.test(res.headers.get('content-type') || '')) { fs.writeFileSync(file, Buffer.from(await res.arrayBuffer())); return; }
    if (attempt === 4) throw new Error(`${url}: ${res.status}`);
    await new Promise((r) => setTimeout(r, attempt * 2000));
  }
}

// The crops: world bbox of the lot + margin, pixel size at RES (or coarser), the ring in pixels
const jobs = [];
for (const lot of PARKING_DATA) {
  if (lot.kind === 'space') continue;
  const xs = lot.ring.filter((_, i) => i % 2 === 0), zs = lot.ring.filter((_, i) => i % 2 === 1);
  const x0 = Math.min(...xs) - MARGIN, x1 = Math.max(...xs) + MARGIN, z0 = Math.min(...zs) - MARGIN, z1 = Math.max(...zs) + MARGIN;
  const res = Math.max(RES, (x1 - x0) / MAX_PX, (z1 - z0) / MAX_PX);
  const w = Math.round((x1 - x0) / res), h = Math.round((z1 - z0) / res);
  const sw = worldToLv95(x0, z1), ne = worldToLv95(x1, z0); // world z grows to the south
  const img = path.join(CACHE, `${lot.id}-${res.toFixed(3)}.jpg`);
  const poly = [];
  for (let i = 0; i < lot.ring.length; i += 2) poly.push([(lot.ring[i] - x0) / res, (lot.ring[i + 1] - z0) / res]);
  jobs.push({ id: lot.id, img, res, poly, x0, z0, w, h, url: `${WMS}?${new URLSearchParams({
    SERVICE: 'WMS', VERSION: '1.3.0', REQUEST: 'GetMap', LAYERS: 'ch.swisstopo.swissimage', STYLES: '', CRS: 'EPSG:2056',
    BBOX: `${sw.E},${sw.N},${ne.E},${ne.N}`, WIDTH: String(w), HEIGHT: String(h), FORMAT: 'image/jpeg'
  })}` });
}
let next = 0;
await Promise.all(Array.from({ length: CONCURRENCY }, async () => {
  while (next < jobs.length) {
    const j = jobs[next++];
    if (!fs.existsSync(j.img)) await fetchRetry(j.url, j.img);
  }
}));
log(`${jobs.length} crops ready`);

// Detection (python)
const jobFile = path.join(CACHE, 'jobs.json'), outFile = path.join(CACHE, 'bays.json');
fs.writeFileSync(jobFile, JSON.stringify(jobs.map(({ id, img, res, poly }) => ({ id, img, res, poly }))));
const debugPng = debugId ? path.resolve(process.argv[debugAt + 2] || path.join(CACHE, `${debugId}-debug.png`)) : null;
execFileSync('python3', ['-I', path.join(DIR, 'parking-bays.py'), jobFile, outFile, ...(debugId ? [debugId, debugPng] : [])], { stdio: 'inherit' });
const found = JSON.parse(fs.readFileSync(outFile, 'utf8'));

// Back to the world frame (pixel x east, pixel y south, like world x and z)
const r1 = (v) => Math.round(v * 10) / 10, r3 = (v) => Math.round(v * 1000) / 1000;
let detected = 0, bayCount = 0, occupied = 0;
const lots = PARKING_DATA.map((lot) => {
  const { bays: _drop, ...rest } = lot;
  const j = jobs.find((q) => q.id === lot.id), f = found[lot.id];
  if (!j || !f || f.bays.length < MIN_BAYS) return rest;
  detected++;
  const bays = f.bays.map(([px, py, hx, hy, w, l, occ]) => {
    bayCount++; occupied += occ;
    return [r1(j.x0 + px * j.res), r1(j.z0 + py * j.res), r3(Math.atan2(hx, hy)), w, l, occ];
  });
  return { ...rest, bays };
});
fs.writeFileSync(OUT, `// js/parking-data.js — GENERATED by tools/fetch-parking.mjs, do not edit by hand.\n// The open-air car parks of Davos (world frame of js/davos-frame.js). © OpenStreetMap contributors (ODbL).\n// Bays painted on the ground (bays: [cx, cz, angle, w, l, occupied]) found in SWISSIMAGE by tools/detect-parking-bays.mjs (© swisstopo).\nexport const PARKING_DATA = ${JSON.stringify(lots)};\n`);
log(`${detected} of ${jobs.length} lots with painted bays found (${bayCount} bays, ${occupied} occupied in the photo); the others keep the procedural layout -> ${OUT}`);
if (debugPng) log(`debug overlay: ${debugPng}`);

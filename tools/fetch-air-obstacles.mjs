// tools/fetch-air-obstacles.mjs — writes js/air-obstacles-data.js: what a helicopter pilot has to know about in the
// Landschaft Davos, for js/air-obstacles.js. From the Federal Office of Civil Aviation FOCA/BAZL's obstacle register
// (ch.bazl.luftfahrthindernis on api3.geo.admin.ch; opendata.swiss terms "open use, must provide the source": © BAZL):
// - 'power': the overhead power lines, their masts (points, with the height above ground) and spans (lines between
//   the masts' tops);
// - 'cable': material and transport cables, hay and blasting cableways (the register's CATENARY), often a single span
//   across a side valley, high above the ground;
// - 'pole': single masts (aerials, measuring masts).
// The lifts' cables (CABLE_CAR) are left out: js/bergbahnen.js builds the lifts from OpenStreetMap. Cranes are left
// out too (they are gone again in a season).
// (The Federal Office of Energy's ch.bfe.elektrische-anlagen_ueber_36 has little to add here: in Davos it is the
// EWD's buried 50 kV cables.)
//
// masts: [x, z, top (m above the frame's H0), height above ground (m), kind]; spans: [x0, z0, top0, x1, z1, top1, kind]
// usage: node tools/fetch-air-obstacles.mjs [--refresh]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { FRAME, WORLD_BOUNDS, lv95ToWorld } from '../js/davos-frame.js';
import { layerFeatures } from './geoadmin.mjs';

const DIR = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(DIR, '..', 'js', 'air-obstacles-data.js');
const log = (...a) => console.log('[air-obstacles]', ...a);
const KINDS = ['power', 'cable', 'pole'];
const KIND = { TRANSMISSION_LINE: 0, CATENARY: 1, POLE: 2 };
const r1 = (v) => Math.round(v * 10) / 10;
const [MIN_X, MIN_Z, MAX_X, MAX_Z] = WORLD_BOUNDS;
const inMap = (x, z) => x >= MIN_X && x <= MAX_X && z >= MIN_Z && z <= MAX_Z;

const features = await layerFeatures('ch.bazl.luftfahrthindernis', FRAME.lv95, { cache: 'geoadmin_luftfahrthindernis', refresh: process.argv.includes('--refresh'), log });
const masts = [], spans = [];
const skipped = {};
for (const f of features) {
  const p = f.properties || {}, g = f.geometry;
  const kind = KIND[p.obstacletype];
  if (kind === undefined || !g) { skipped[p.obstacletype] = (skipped[p.obstacletype] || 0) + 1; continue; }
  const world = ([E, N, H]) => { const w = lv95ToWorld(E, N); return [r1(w.x), r1(w.z), r1((H ?? p.topelevationamsl) - FRAME.H0)]; };
  if (g.type === 'Point') {
    const [x, z, top] = world(g.coordinates);
    if (inMap(x, z)) masts.push([x, z, top, r1(p.maxheightagl || 0), kind]);
  } else if (g.type === 'LineString') {
    for (let i = 1; i < g.coordinates.length; i++) {
      const a = world(g.coordinates[i - 1]), b = world(g.coordinates[i]);
      if (inMap(a[0], a[1]) && inMap(b[0], b[1])) spans.push([...a, ...b, kind]);
    }
  }
}
// (a mast listed twice, by two neighbouring spans' entries, once)
const seen = new Set();
const unique = masts.filter((m) => { const k = `${Math.round(m[0])},${Math.round(m[1])},${m[4]}`; if (seen.has(k)) return false; seen.add(k); return true; });

const data = {
  source: 'Bundesamt für Zivilluftfahrt BAZL, ch.bazl.luftfahrthindernis, opendata.swiss terms of use (open use, must provide the source)',
  fetched: new Date().toISOString().slice(0, 10),
  kinds: KINDS,
  masts: unique,
  spans
};
fs.writeFileSync(OUT, `// js/air-obstacles-data.js — GENERATED by tools/fetch-air-obstacles.mjs, do not edit by hand.\n// The registered air navigation obstacles of Davos (power lines, cables, masts; world frame of js/davos-frame.js,\n// heights above its H0). © BAZL.\nexport const AIR_OBSTACLES = ${JSON.stringify(data)};\n`);
const spanLength = (s) => Math.hypot(s[3] - s[0], s[4] - s[1]);
log(`${unique.length} masts (${KINDS.map((k, i) => `${k} ${unique.filter((m) => m[4] === i).length}`).join(', ')}), ${spans.length} spans (${KINDS.map((k, i) => `${k} ${spans.filter((s) => s[6] === i).length}`).join(', ')}), longest span ${Math.round(Math.max(...spans.map(spanLength)))} m`);
log('left out:', JSON.stringify(skipped));
log(`wrote ${path.relative(process.cwd(), OUT)} (${fs.statSync(OUT).size} bytes)`);

// tools/fetch-parking.mjs — writes js/parking-data.js: the open-air car parks of Davos for js/parking.js. From
// OpenStreetMap (tools/data/q_davos_parking.overpassql): amenity=parking areas (surface lots, street-side and lane
// parking; multi-storey and underground car parks and garage rows are left out, their cars are out of sight), and
// amenity=parking_space areas (single marked bays). Each lot is a ring in the world frame (js/davos-frame.js), with its
// capacity when mapped.
// usage: node tools/fetch-parking.mjs   (re-download: delete tools/data/cache/osm_davos_parking.json)
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { WORLD_BOUNDS, lonLatToWorld } from '../js/davos-frame.js';

const DIR = path.dirname(fileURLToPath(import.meta.url));
const CACHE = path.join(DIR, 'data', 'cache', 'osm_davos_parking.json');
const OUT = path.join(DIR, '..', 'js', 'parking-data.js');
const log = (...a) => console.log('[parking]', ...a);

if (!fs.existsSync(CACHE)) {
  fs.mkdirSync(path.dirname(CACHE), { recursive: true });
  execFileSync('bash', [path.join(DIR, 'overpass.sh'), CACHE, path.join(DIR, 'data', 'q_davos_parking.overpassql')], { stdio: 'inherit' });
}
const osm = JSON.parse(fs.readFileSync(CACHE, 'utf8'));
const [minX, minZ, maxX, maxZ] = WORLD_BOUNDS;
const r1 = (v) => Math.round(v * 10) / 10;
const HIDDEN = /^(underground|multi-storey|garage_boxes|rooftop|carports?)$/;

// Outer rings of a way or a multipolygon relation, as world [x, z] points
function rings(e) {
  if (e.type === 'way' && e.geometry) return [e.geometry];
  if (e.type === 'relation') return (e.members || []).filter((m) => m.role === 'outer' && m.geometry).map((m) => m.geometry);
  return [];
}

const lots = [];
for (const e of osm.elements) {
  const t = e.tags || {};
  const space = t.amenity === 'parking_space';
  if (t.amenity !== 'parking' && !space) continue;
  if (HIDDEN.test(t.parking || '') || t.access === 'no') continue;
  for (const g of rings(e)) {
    const pts = g.map((p) => lonLatToWorld(p.lon, p.lat));
    if (pts.length < 4) continue;
    const xs = pts.map((p) => p.x), zs = pts.map((p) => p.z);
    if (Math.max(...xs) < minX || Math.min(...xs) > maxX || Math.max(...zs) < minZ || Math.min(...zs) > maxZ) continue;
    lots.push({
      id: `${e.type[0]}${e.id}`,
      kind: space ? 'space' : t.parking === 'street_side' || t.parking === 'lane' ? 'street' : 'surface',
      name: t.name || '',
      capacity: Number.parseInt(t.capacity, 10) || null,
      ring: pts.flatMap((p) => [r1(p.x), r1(p.z)])
    });
  }
}
fs.writeFileSync(OUT, `// js/parking-data.js — GENERATED by tools/fetch-parking.mjs, do not edit by hand.\n// The open-air car parks of Davos (world frame of js/davos-frame.js). © OpenStreetMap contributors (ODbL).\nexport const PARKING_DATA = ${JSON.stringify(lots)};\n`);
const by = (k) => lots.filter((l) => l.kind === k).length;
log(`${lots.length} lots (${by('surface')} surface, ${by('street')} street side / lane, ${by('space')} single bays) -> ${OUT}`);

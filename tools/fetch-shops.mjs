// tools/fetch-shops.mjs — writes js/shops-data.js: the shops, restaurants, hotels, banks… of Davos with the lettering and
// colours of their signs. Businesses from OpenStreetMap (tools/data/q_davos_shops.overpassql: named shop=*, gastronomy,
// banks, pharmacies, post offices, hotels, museums); sign styles from tools/data/brands.json (the brand colours of the
// chains and of notable local businesses, researched by hand; drawn in code by js/shops.js, no logo artwork) by brand or
// name, else by kind; plus the businesses OSM lacks ("extra", positioned from their address).
// usage: node tools/fetch-shops.mjs   (re-download: delete tools/data/cache/osm_davos_shops.json)
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { WORLD_BOUNDS, lonLatToWorld, lv95ToWorld } from '../js/davos-frame.js';

const DIR = path.dirname(fileURLToPath(import.meta.url));
const CACHE = path.join(DIR, 'data', 'cache', 'osm_davos_shops.json');
const OUT = path.join(DIR, '..', 'js', 'shops-data.js');
const log = (...a) => console.log('[shops]', ...a);

if (!fs.existsSync(CACHE)) {
  fs.mkdirSync(path.dirname(CACHE), { recursive: true });
  execFileSync('bash', [path.join(DIR, 'overpass.sh'), CACHE, path.join(DIR, 'data', 'q_davos_shops.overpassql')], { stdio: 'inherit' });
}
const osm = JSON.parse(fs.readFileSync(CACHE, 'utf8'));
const { brands, kinds, extra } = JSON.parse(fs.readFileSync(path.join(DIR, 'data', 'brands.json'), 'utf8'));
const patterns = brands.map((b) => ({ ...b, re: new RegExp(b.match, 'i') }));
const [minX, minZ, maxX, maxZ] = WORLD_BOUNDS;
const r1 = (v) => Math.round(v * 10) / 10;

function styleFor(name, brand, kind) {
  const b = patterns.find((p) => p.re.test(brand || '') || p.re.test(name));
  const k = kinds[kind] || kinds.default;
  const s = { ...k, ...(b ? { ...b, re: undefined, match: undefined } : {}) };
  let text = s.text || name;
  if (s.case === 'upper') text = text.toUpperCase();
  else if (s.case === 'lower') text = text.toLowerCase();
  const out = { text, colour: s.colour, background: s.background, weight: s.weight, font: s.font, scale: s.scale ?? 1 };
  for (const key of ['border', 'sub', 'mark', 'hanging']) if (s[key] !== undefined) out[key] = s[key];
  if (b) out.chain = true;
  return out;
}

const shops = [], seen = new Set();
for (const e of osm.elements) {
  const t = e.tags || {};
  const lat = e.lat ?? e.center?.lat, lon = e.lon ?? e.center?.lon;
  if (lat == null || !t.name) continue;
  const { x, z } = lonLatToWorld(lon, lat);
  if (x < minX || x > maxX || z < minZ || z > maxZ) continue;
  const kind = t.shop || t.amenity || t.tourism || 'default';
  const key = `${t.name}@${Math.round(x / 5)},${Math.round(z / 5)}`;
  if (seen.has(key)) continue;
  seen.add(key);
  shops.push({ name: t.name, kind, x: r1(x), z: r1(z), osm: `${e.type[0]}${e.id}`, brand: styleFor(t.name, t.brand, kind) });
}
for (const s of extra) {
  const { x, z } = lv95ToWorld(s.E, s.N);
  shops.push({ name: s.name, kind: s.kind, x: r1(x), z: r1(z), osm: null, brand: styleFor(s.name, null, s.kind) });
}
shops.sort((a, b) => a.x - b.x || a.z - b.z);
fs.writeFileSync(OUT, `// js/shops-data.js — GENERATED by tools/fetch-shops.mjs, do not edit by hand.\n// Businesses of Davos and their sign styles (world frame of js/davos-frame.js). © OpenStreetMap contributors (ODbL).\nexport const SHOPS_DATA = ${JSON.stringify(shops)};\n`);
log(`${shops.length} businesses (${shops.filter((s) => s.brand.chain).length} with a researched brand style) -> ${OUT}`);
